import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workerRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const siteRoot = path.resolve(workerRoot, "..");
const collections = [
  ["godsofdestiny", "godsofdestiny-data.js", "GODSOFDESTINY_CARDS"],
  ["cardnft1", "cardnft-data.js", "CARD_NFTS"],
  ["cardnft2", "cardnft2-data.js", "CARD_NFT_2S"],
  ["poncho", "poncho-data.js", "PONCHO_CARDS"],
  ["limited", "limited-data.js", "LIMITED_CARDS"],
  ["cloudcastle", "cloudcastle-data.js", "CLOUDCASTLE_CARDS"],
  ["badhand", "badhand-data.js", "BADHAND_CARDS"],
  ["badhand2", "badhand2-data.js", "BADHAND2_CARDS"],
  ["jpegs", "jpegs-data.js", "JPEGS_CARDS"],
  ["nolegs", "nolegs-data.js", "NOLEGS_CARDS"],
  ["playcards", "playcards-data.js", "PLAYCARDS_CARDS"],
  ["kardmane", "kardmane-data.js", "KARDMANE_CARDS"],
  ["cloudcastles", "cloudcastles-data.js", "CLOUDCASTLES_CARDS"],
  ["sweetcurse", "sweetcurse-data.js", "SWEETCURSE_CARDS"],
  ["winloop", "winloop-data.js", "WINLOOP_CARDS"],
  ["mtgnft", "mtgnft-data.js", "MTGNFT_CARDS"],
  ["igorsquest", "igorsquest-data.js", "IGORSQUEST_CARDS"],
  ["clear", "clear-data.js", "CLEAR_CARDS"],
  ["reflection2", "reflection2-data.js", "REFLECTION2_CARDS"],
];

const mintToCard = new Map();
const referenceToCard = new Map();
const collectionRanges = [];
let cardIndex = 0;

for (const [collectionId, filename, exportName] of collections) {
  // Catalogs are self-contained ES modules; a data URL also works when the site
  // repository has no package.json module declaration on newer Node versions.
  const source = await readFile(path.join(siteRoot, filename), "utf8");
  const module = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
  const cards = module[exportName];
  if (!Array.isArray(cards)) throw new Error(`Invalid ${collectionId} card data`);
  collectionRanges.push([collectionId, cardIndex, cardIndex + cards.length]);
  for (let collectionIndex = 0; collectionIndex < cards.length; collectionIndex += 1) {
    const card = cards[collectionIndex];
    for (const mint of [card?.mint, ...(Array.isArray(card?.mints) ? card.mints : [])]) {
      const normalizedMint = String(mint || "").trim();
      if (normalizedMint) mintToCard.set(normalizedMint, cardIndex);
    }
    const titleMatch = String(card?.title || "").match(/^card\s+#?\s*(\d+)$/i);
    const number = Number.isInteger(card?.number)
      ? card.number
      : titleMatch
        ? Number.parseInt(titleMatch[1], 10)
        : null;
    if (Number.isInteger(number)) {
      referenceToCard.set(`${collectionId}:${number}`, cardIndex);
    }
    cardIndex += 1;
  }
}

const mintIndex = [...mintToCard].flat();
const referenceIndex = [...referenceToCard].flat();
const version = createHash("sha256")
  .update(JSON.stringify([collectionRanges, mintIndex, referenceIndex])).digest("hex");
const header = "// Generated by worker/scripts/build-supported-card-index.mjs.\n";
const manifest = header
  + `export const SUPPORTED_WALLET_CATALOG_VERSION = ${JSON.stringify(version)};\n`
  + `export const SUPPORTED_WALLET_CARD_COUNT = ${cardIndex};\n`;
const output = manifest
  + `export const SUPPORTED_CARD_COLLECTION_RANGES = ${JSON.stringify(collectionRanges)};\n`
  + `export const SUPPORTED_CARD_MINT_INDEX = ${JSON.stringify(mintIndex)};\n`
  + `export const SUPPORTED_CARD_REFERENCE_INDEX = ${JSON.stringify(referenceIndex)};\n`;
for (const [file, content] of [
  [path.join(workerRoot, "src", "supported-card-index.js"), output],
  [path.join(siteRoot, "supported-wallet-catalog.mjs"), manifest],
]) {
  if (process.argv.includes("--check")) {
    if (await readFile(file, "utf8") !== content) throw new Error(`Regenerate outdated wallet catalog: ${file}`);
  } else await writeFile(file, content);
}
console.log(`Indexed ${mintToCard.size} mints and ${referenceToCard.size} card references (${collectionRanges.length} collections).`);
