import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../../',import.meta.url);
const source=await readFile(new URL('app.js',root),'utf8');
const specs=source.slice(source.indexOf('const COLLECTION_DATA_SPECS ='),source.indexOf('const REQUESTED_COLLECTION_ID'));
const ids=[],drifellas=[];
for(const match of specs.matchAll(/(\w+):\s*\{\s*module:\s*"\.\/([^"?]+)[^"]*",\s*exportName:\s*"([^"]+)"/g)){
 const [,collection,file,exportName]=match;
 const cards=(await import(new URL(file,root)))[exportName];
 cards.forEach((card,index)=>ids.push(card.stableId||`${collection}:${card.mint||card.title||index}`));
 if(collection==='poncho'||collection==='limited')for(const card of cards) {
  if(collection==='poncho'?/^poncho drifella\b/i.test(card.title):/^drifella card [12]$/i.test(card.title))drifellas.push(card.stableId);
 }
}
if(!ids.length)throw Error('Empty showroom catalog');
await writeFile(new URL('../src/showroom-catalog.js',import.meta.url),`// Generated by scripts/build-showroom-catalog.mjs\nexport const SHOWROOM_CARD_IDS=new Set(${JSON.stringify(ids)});\n`);
console.log(`Showroom catalog: ${ids.length} cards`);
const {CARD_NFT_2S}=await import(new URL('cardnft2-data.js',root));
const {CARD_NFT_2_TRAITS}=await import(new URL('cardnft2-traits.js',root));
if(CARD_NFT_2S.length!==CARD_NFT_2_TRAITS.length)throw Error('Card NFT 2 trait catalog is out of sync');
const mosaics=CARD_NFT_2S.filter((card,index)=>CARD_NFT_2_TRAITS[index].entries.some(entry=>
 entry.category.toLowerCase()==='rarity'&&entry.value.toLowerCase()==='pixel mosaic')).map(card=>card.stableId);
await writeFile(new URL('../src/showroom-ritual-catalog.js',import.meta.url),
 `// Generated from collection titles and Rarity metadata by scripts/build-showroom-catalog.mjs.\nexport const DRIFELLA_IDS=new Set(${JSON.stringify(drifellas)});\nexport const PIXEL_MOSAIC_IDS=new Set(${JSON.stringify(mosaics)});\n`);
console.log(`Ritual catalog: ${drifellas.length} Drifellas, ${mosaics.length} Pixel Mosaic cards`);
