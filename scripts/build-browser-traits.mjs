import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_DIR = path.join(ROOT, "browser-traits");
const CATALOG_PATH = path.join(ROOT, "browser-traits-catalog.js");

const COLLECTIONS = [
  ["cardnft1", "cardnft-traits.js", "CARD_NFT_TRAIT_CATEGORIES", "CARD_NFT_TRAITS"],
  ["cardnft2", "cardnft2-traits.js", "CARD_NFT_2_TRAIT_CATEGORIES", "CARD_NFT_2_TRAITS"],
  ["poncho", "poncho-traits.js", "PONCHO_TRAIT_CATEGORIES", "PONCHO_TRAITS"],
  ["limited", "limited-traits.js", "LIMITED_TRAIT_CATEGORIES", "LIMITED_TRAITS"],
  ["cloudcastle", "cloudcastle-traits.js", "CLOUDCASTLE_TRAIT_CATEGORIES", "CLOUDCASTLE_TRAITS"],
  ["badhand", "badhand-traits.js", "BADHAND_TRAIT_CATEGORIES", "BADHAND_TRAITS"],
  ["badhand2", "badhand2-traits.js", "BADHAND2_TRAIT_CATEGORIES", "BADHAND2_TRAITS"],
  ["jpegs", "jpegs-traits.js", "JPEGS_TRAIT_CATEGORIES", "JPEGS_TRAITS"],
  ["nolegs", "nolegs-traits.js", "NOLEGS_TRAIT_CATEGORIES", "NOLEGS_TRAITS"],
  ["playcards", "playcards-traits.js", "PLAYCARDS_TRAIT_CATEGORIES", "PLAYCARDS_TRAITS"],
  ["kardmane", "kardmane-traits.js", "KARDMANE_TRAIT_CATEGORIES", "KARDMANE_TRAITS"],
  ["cloudcastles", "cloudcastles-traits.js", "CLOUDCASTLES_TRAIT_CATEGORIES", "CLOUDCASTLES_TRAITS"],
  ["sweetcurse", "sweetcurse-traits.js", "SWEETCURSE_TRAIT_CATEGORIES", "SWEETCURSE_TRAITS"],
  ["winloop", "winloop-traits.js", "WINLOOP_TRAIT_CATEGORIES", "WINLOOP_TRAITS"],
  ["mtgnft", "mtgnft-traits.js", "MTGNFT_TRAIT_CATEGORIES", "MTGNFT_TRAITS"],
  ["igorsquest", "igorsquest-traits.js", "IGORSQUEST_TRAIT_CATEGORIES", "IGORSQUEST_TRAITS"],
  ["reflection2", "reflection2-traits.js", "REFLECTION2_TRAIT_CATEGORIES", "REFLECTION2_TRAITS"],
];

await mkdir(OUTPUT_DIR, { recursive: true });

const catalog = {};
for (const [id, sourceFile, categoriesExport, traitsExport] of COLLECTIONS) {
  const sourceUrl = new URL(`../${sourceFile}`, import.meta.url);
  sourceUrl.searchParams.set("build", String(Date.now()));
  const source = await import(sourceUrl.href);
  const categories = source[categoriesExport];
  const traits = source[traitsExport];
  if (!Array.isArray(categories) || !Array.isArray(traits)) {
    throw new Error(`Invalid trait exports for ${id}`);
  }

  const categoryIndexes = new Map(categories.map((category, index) => [String(category).trim(), index]));
  const values = [];
  const valueIndexes = new Map();
  const getValueIndex = (value) => {
    const normalized = String(value ?? "").trim();
    if (!normalized) return -1;
    if (!valueIndexes.has(normalized)) {
      valueIndexes.set(normalized, values.length);
      values.push(normalized);
    }
    return valueIndexes.get(normalized);
  };

  const rows = traits.map((record) => {
    const row = [];
    if (Array.isArray(record?.entries)) {
      for (const entry of record.entries) {
        const categoryIndex = categoryIndexes.get(String(entry?.category ?? "").trim());
        const valueIndex = getValueIndex(entry?.value);
        if (Number.isInteger(categoryIndex) && valueIndex >= 0) {
          row.push(categoryIndex, valueIndex);
        }
      }
    } else {
      for (const [categoryIndex, value] of (record?.values || []).entries()) {
        const valueIndex = getValueIndex(value);
        if (categoryIndex < categories.length && valueIndex >= 0) {
          row.push(categoryIndex, valueIndex);
        }
      }
    }
    return row;
  });

  const moduleText = [
    "// Generated by scripts/build-browser-traits.mjs",
    `export const TRAIT_VALUE_DICTIONARY=${JSON.stringify(values)};`,
    `export const TRAIT_ROWS=${JSON.stringify(rows)};`,
    "",
  ].join("\n");
  await writeFile(path.join(OUTPUT_DIR, `${id}.js`), moduleText);
  catalog[id] = {
    categories,
    module: `./browser-traits/${id}.js?v=browser-traits-10`,
    records: rows.length,
  };
}

await writeFile(
  CATALOG_PATH,
  [
    "// Generated by scripts/build-browser-traits.mjs",
    `export const BROWSER_TRAIT_CATALOG=${JSON.stringify(catalog)};`,
    "",
  ].join("\n"),
);

console.log(`Built browser trait data for ${COLLECTIONS.length} collections.`);
