import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
if(!process.argv[2])throw Error('Usage: node scripts/build-minote-studio-assets.mjs /path/to/local-studio');
const src=resolve(process.argv[2]),out=new URL('../minotecurator',import.meta.url).pathname;
const {sharp,assetPath}=await import(pathToFileURL(src+'/scripts/local-assets.mjs'));
for(const dir of ['names','originals','thumbs'])await mkdir(out+'/assets/'+dir,{recursive:true});
const items=JSON.parse(await readFile(src+'/.local/collection.json'));
await writeFile(out+'/collection.json',JSON.stringify(items.map(({id,name,width,height,nameWidth,nameHeight})=>({id,name,width,height,nameWidth,nameHeight,available:true}))));
const seed=JSON.parse(await readFile(src+'/.local/edits.json'));await writeFile(out+'/initial-edits.json',JSON.stringify(seed));
for(const file of ['strip.png','body.png','body-crop.png'])await copyFile(await assetPath(file),out+'/assets/'+file);
let cursor=0,done=0;
await Promise.all(Array.from({length:3},async()=>{while(cursor<items.length){const item=items[cursor++];
 await sharp(await assetPath(`names/${item.id}.png`)).webp({lossless:true,effort:3}).toFile(out+`/assets/names/${item.id}.webp`);
 const art=await assetPath(`originals/${item.id}.jpg`);
 await sharp(art).resize({width:2000,height:2800,fit:'inside',withoutEnlargement:true}).webp({quality:85,effort:4}).toFile(out+`/assets/originals/${item.id}.webp`);
 await sharp(art).resize({width:420,withoutEnlargement:true}).webp({quality:82,effort:3}).toFile(out+`/assets/thumbs/${item.id}.webp`);
 if(++done%200===0)console.log(done);
}}));console.log('Complete',done);
